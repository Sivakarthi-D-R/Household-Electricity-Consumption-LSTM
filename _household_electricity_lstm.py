# CELL 1: Imports and reproducibility
"""

import random
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import tensorflow as tf

from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from tensorflow.keras import Sequential
from tensorflow.keras.layers import Input, LSTM, Dense, Dropout
from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau

SEED = 42
random.seed(SEED)
np.random.seed(SEED)
tf.random.set_seed(SEED)

"""# CELL 2: Load and preprocess dataset"""

df = pd.read_csv(
    "household_power_consumption.csv",
    sep=",",
    na_values=["?"],
    low_memory=False
)

if "index" in df.columns:
    df = df.drop(columns=["index"])

required_cols = {"Date", "Time", "Global_active_power"}
missing_cols = required_cols - set(df.columns)
if missing_cols:
    raise ValueError(f"Missing required columns: {missing_cols}")

df["Datetime"] = pd.to_datetime(
    df["Date"].astype(str) + " " + df["Time"].astype(str),
    format="%m/%d/%y %H:%M:%S",
    errors="coerce"
)

df = df.dropna(subset=["Datetime"]).sort_values("Datetime")
df = df.drop_duplicates(subset=["Datetime"]).set_index("Datetime")

df["Global_active_power"] = pd.to_numeric(
    df["Global_active_power"], errors="coerce"
)


# Select valid readings without filling missing values
data = df[["Global_active_power"]].copy()
data = data.dropna(subset=["Global_active_power"])
data = data[~data.index.duplicated(keep="first")].sort_index()

# Find continuous one-minute segments
gap = data.index.to_series().diff().ne(pd.Timedelta(minutes=1))
segment_id = gap.cumsum()

segments = data.groupby(segment_id, sort=False)
data = segments.get_group(segments.size().idxmax()).copy()

print("Valid consecutive records:", len(data))
print("Start:", data.index[0])
print("End:", data.index[-1])
print(
    "All timestamps one minute apart:",
    data.index.to_series().diff().iloc[1:].eq(
        pd.Timedelta(minutes=1)
    ).all()
)


if len(data) <= 100:
    raise ValueError("Not enough valid records to create time-series sequences.")

print("\nPreprocessing complete")
print("Dataset shape:", data.shape)
print("Missing values:", int(data.isna().sum().sum()))
print(data.head())

"""# CELL 3: Chronological split and normalization"""

values = data["Global_active_power"].to_numpy(dtype=np.float32).reshape(-1, 1)

split = int(len(values) * 0.80)
WINDOW = 60

# Fit the scaler only on training data.
scaler = MinMaxScaler()
train_scaled = scaler.fit_transform(values[:split])
test_scaled = scaler.transform(values[split:])

# Include the final 60 training measurements as context for test predictions.
test_context = np.vstack([train_scaled[-WINDOW:], test_scaled])
all_scaled = np.vstack([train_scaled, test_scaled])

print("\nTotal records:", len(values))
print("Training records:", split)
print("Testing records:", len(values) - split)
print("Window size:", WINDOW)

"""# CELL 4: Create sliding-window sequences"""

def create_sequences(series, window):
    X, y = [], []
    for i in range(window, len(series)):
        X.append(series[i - window:i, 0])
        y.append(series[i, 0])

    X = np.asarray(X, dtype=np.float32).reshape(-1, window, 1)
    y = np.asarray(y, dtype=np.float32)
    return X, y

# Training sequences use only the training period.
X_train, y_train = create_sequences(train_scaled, WINDOW)

# Test sequences use earlier observations as context for each test prediction.
X_test, y_test = create_sequences(test_context, WINDOW)

print("Training input shape:", X_train.shape)
print("Testing input shape:", X_test.shape)

"""# CELL 5: Build LSTM model"""

model = Sequential([
    Input(shape=(WINDOW, 1)),
    LSTM(64, return_sequences=True),
    Dropout(0.2),
    LSTM(32),
    Dense(16, activation="relu"),
    Dense(1)
])

model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=0.001),
    loss="mse",
    metrics=["mae"]
)

model.summary()

"""# CELL 6: Train the model"""

early_stop = EarlyStopping(
    monitor="val_loss",
    patience=4,
    restore_best_weights=True,
    verbose=1
)

reduce_lr = ReduceLROnPlateau(
    monitor="val_loss",
    factor=0.5,
    patience=2,
    min_lr=1e-5,
    verbose=1
)

history = model.fit(
    X_train,
    y_train,
    epochs=15,
    batch_size=64,
    validation_split=0.1,
    shuffle=False,
    callbacks=[early_stop, reduce_lr],
    verbose=1
)

"""# CELL 7: Evaluate LSTM on the test set"""

pred_scaled = model.predict(X_test, verbose=0).reshape(-1, 1)

actual = scaler.inverse_transform(y_test.reshape(-1, 1)).ravel()
predicted = scaler.inverse_transform(pred_scaled).ravel()

mae = mean_absolute_error(actual, predicted)
rmse = np.sqrt(mean_squared_error(actual, predicted))
r2 = r2_score(actual, predicted)

print("\n========== LSTM TEST RESULTS ==========")
print(f"MAE  : {mae:.4f} kW")
print(f"RMSE : {rmse:.4f} kW")
print(f"R²   : {r2:.4f}")

"""
# CELL 8: The only graph — actual versus predicted consumption"""

show_n = min(500, len(actual))

plt.figure(figsize=(14, 5))
plt.plot(actual[:show_n], label="Actual Consumption", linewidth=1.5)
plt.plot(predicted[:show_n], label="LSTM Predicted Consumption", linewidth=1.2)
plt.title("Household Electricity Consumption Forecasting Using LSTM")
plt.xlabel("Test Minute")
plt.ylabel("Global Active Power (kW)")
plt.legend()
plt.grid(True)
plt.tight_layout()
plt.show()

"""
# CELL 9: Display first 20 test predictions and their errors"""

n_show = min(20, len(actual))

test_results = pd.DataFrame({
    "Actual (kW)": actual[:n_show],
    "Predicted (kW)": predicted[:n_show]
})

test_results["Absolute Error (kW)"] = (
    test_results["Actual (kW)"] - test_results["Predicted (kW)"]
).abs()

print("\n========== FIRST 20 TEST PREDICTIONS ==========")
print(test_results.round(4).to_string(index=False))

"""# CELL 10: Predict consumption for the next minute after the dataset"""

# Predict electricity consumption for the next 20 minutes

steps = 20

# Start with the latest 60 observations
seq = all_scaled[-WINDOW:].copy()

future_scaled = []

for i in range(steps):
    # Predict the next minute
    next_scaled = model.predict(
        seq.reshape(1, WINDOW, 1),
        verbose=0
    )[0, 0]

    future_scaled.append(next_scaled)

    # Add the prediction and remove the oldest observation
    seq = np.vstack([seq[1:], [[next_scaled]]])

# Convert predictions back to kW
future_scaled = np.array(future_scaled).reshape(-1, 1)
future_values = scaler.inverse_transform(future_scaled).flatten()

# Display forecast results
forecast_results = pd.DataFrame({
    "Minute Ahead": range(1, steps + 1),
    "Predicted Consumption (kW)": future_values
})

print("===== NEXT 20 MINUTES FORECAST =====")
print(forecast_results.round(4).to_string(index=False))

# Plot the 20-minute forecast
plt.figure(figsize=(10, 4))
plt.plot(
    forecast_results["Minute Ahead"],
    forecast_results["Predicted Consumption (kW)"],
    marker="o",
    label="LSTM Forecast"
)
plt.title("Next 20 Minutes Electricity Consumption Forecast")
plt.xlabel("Minutes Ahead")
plt.ylabel("Predicted Power (kW)")
plt.xticks(range(1, 21))
plt.grid(True)
plt.legend()
plt.tight_layout()
plt.show()